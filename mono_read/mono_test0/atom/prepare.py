"""Adapt the fixed gfx1250 supplier assembly to an ordinary device function."""
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent
SOURCE_SHA = '4050f8e1eacf2463c98adeb8f2aeee2ca93e2792de3a43e58088cbd36a05a711'
SYMBOL = 'mono_dq_convert_device'
source = (ROOT / 'dq_convert.original.s').read_bytes()
if hashlib.sha256(source).hexdigest() != SOURCE_SHA:
    raise SystemExit('Original assembly changed; re-audit ABI/registers/layout before adapting it')
records = []
for line in source.decode().splitlines():
    match = re.fullmatch(r'(.*?) // original \+0x([0-9a-f]+): ([0-9A-F ]+)', line)
    if match:
        records.append((int(match[2], 16), match[1], match[3].split()))
assert len(records) == 292
assert records[-1] == (0x5f4, 's_endpgm', ['BFB00000'])
body_text = '\n'.join(inst for _, inst, _ in records)
assert not re.search(r'\b(?:s5|s4[0-7]|v4[89]|v5[0-4])\b', body_text)
assert not re.search(r'\b(?:scratch_|s_barrier|ds_|s_(?:c?branch|swappc|setpc))', body_text)
patches = {
    # A device argument is an ordinary global pointer, not a tagged kernarg
    # pointer. Keep its upper address bits instead of truncating them to 48 bits.
    0x04: ('s_and_b32 s1, s1, 0xffff', ['s_nop 0', 's_nop 0']),
    0x64: ('s_mov_b32 s2, ttmp9', ['s_mov_b32 s2, 0']),
    0x68: ('s_and_b32 s3, ttmp7, 0xffff', ['s_mov_b32 s3, 0', 's_nop 0']),
    0x70: ('s_bfe_u32 s4, ttmp7, 0x100010', ['s_mov_b32 s4, 0', 's_nop 0']),
    0x78: ('s_bfe_u32 s24, ttmp8, 0x50019', ['s_nop 0', 's_nop 0']),
}
# Each replacement retains its original length, permitting byte-by-byte audits.
for offset, old, words in records:
    if offset in patches:
        expected, replacement = patches[offset]
        assert old == expected and len(replacement) == len(words)

prefix = '''// Generated by prepare.py from the fixed original. Ordinary gfx1250 device ABI.
// args: v0:v1 (uniform global pointer), linear_tid: v2 (threadIdx.x).
// Full EXEC, wave32, VGPR bank 0. Whole 128/256-thread CTA calls uniformly.
// Callee-saved registers are physically restored here; no custom call regmask.
.amdgcn_target "amdgcn-amd-amdhsa--gfx1250"
.amdhsa_code_object_version 6
.text
.globl mono_dq_convert_device
.hidden mono_dq_convert_device
.p2align 6
.type mono_dq_convert_device,@function
mono_dq_convert_device:
    s_wait_loadcnt 0
    s_wait_storecnt 0
    s_wait_dscnt 0
    s_wait_kmcnt 0
    s_wait_xcnt 0
    s_waitcnt_depctr 0
    v_readfirstlane_b32 s0, v2
    s_waitcnt_depctr 0
    s_lshr_b32 s0, s0, 5
    s_cmp_ge_u32 s0, 4
    s_cbranch_scc1 .Ldevice_return

    // The original writes s30:s38, including RA/SP/FP. These backups are
    // caller-clobbered and never touched by the original leaf body.
    s_mov_b64 s[40:41], s[30:31]
    s_mov_b64 s[42:43], s[32:33]
    s_mov_b64 s[44:45], s[34:35]
    s_mov_b64 s[46:47], s[36:37]
    s_mov_b32 s5, s38
    v_mov_b32_e32 v48, v40
    v_mov_b32_e32 v49, v41
    v_mov_b32_e32 v50, v42
    v_mov_b32_e32 v51, v43
    v_mov_b32_e32 v52, v44
    v_mov_b32_e32 v53, v45

    // Keep the caller's FP environment, then match the supplier descriptor.
    s_getreg_b32 s0, hwreg(HW_REG_MODE, 0, 8)
    v_mov_b32_e32 v54, s0
    s_waitcnt_depctr 0
    s_setreg_imm32_b32 hwreg(HW_REG_MODE, 0, 8), 0xc0
    s_nop 7

    // Bridge normal device arguments to the original kernel's input registers.
    v_readfirstlane_b32 s0, v0
    v_readfirstlane_b32 s1, v1
    v_readfirstlane_b32 s24, v2
    s_waitcnt_depctr 0
    s_lshr_b32 s24, s24, 5
    v_and_b32_e32 v0, 31, v2
    s_waitcnt_depctr 0
.Ldq_payload:
'''
lines = []
manifest = []
for offset, inst, words in records[:-1]:
    if offset in patches:
        replacement = patches[offset][1]
        lines.append(f'    // Replaced original +0x{offset:04x}: {inst}')
        lines.extend('    ' + op for op in replacement)
        manifest.append({'original_offset': offset, 'old_words': words, 'new_instructions': replacement})
    else:
        lines.append(f'    {inst} // original +0x{offset:04x}: {" ".join(words)}')
suffix = '''
.Ldq_payload_end:
    // Ordinary return is not s_endpgm: explicitly complete output stores.
    s_wait_loadcnt 0
    s_wait_storecnt 0
    s_wait_dscnt 0
    s_wait_kmcnt 0
    s_wait_xcnt 0
    s_waitcnt_depctr 0
    v_readfirstlane_b32 s0, v54
    s_waitcnt_depctr 0
    s_setreg_b32 hwreg(HW_REG_MODE, 0, 8), s0
    s_nop 7

    v_mov_b32_e32 v40, v48
    v_mov_b32_e32 v41, v49
    v_mov_b32_e32 v42, v50
    v_mov_b32_e32 v43, v51
    v_mov_b32_e32 v44, v52
    v_mov_b32_e32 v45, v53
    s_mov_b64 s[30:31], s[40:41]
    s_mov_b64 s[32:33], s[42:43]
    s_mov_b64 s[34:35], s[44:45]
    s_mov_b64 s[36:37], s[46:47]
    s_mov_b32 s38, s5
    s_waitcnt_depctr 0
.Ldevice_return:
    s_setpc_b64 s[30:31]
.Ldevice_end:
.size mono_dq_convert_device, .Ldevice_end-mono_dq_convert_device

// Resource information only. ELF linking does not automatically merge these
// values into a caller's HSA descriptor; see resources.json and the guide.
.set mono_dq_convert_device.num_vgpr, 55
.set mono_dq_convert_device.num_agpr, 0
.set mono_dq_convert_device.numbered_sgpr, 48
.set mono_dq_convert_device.num_named_barrier, 0
.set mono_dq_convert_device.private_seg_size, 0
.set mono_dq_convert_device.uses_vcc, 0
.set mono_dq_convert_device.uses_flat_scratch, 0
.set mono_dq_convert_device.has_dyn_sized_stack, 0
.set mono_dq_convert_device.has_recursion, 0
.set mono_dq_convert_device.has_indirect_call, 0
.p2align 6
.fill 96, 4, 0xbf9f0000
.section .note.GNU-stack,"",@progbits
'''
(ROOT / 'dq_convert.device.s').write_text(prefix + '\n'.join(lines) + '\n' + suffix)
resources = {
    'symbol': SYMBOL, 'target': 'gfx1250', 'wave_size': 32, 'elf_type': 'ET_REL',
    'calling_convention': 'ordinary HIP/LLVM C device function; default CSR_AMDGPU',
    'vgpr_count': 55, 'numbered_sgpr_count': 48, 'agpr_count': 0,
    'private_frame_bytes': 0, 'lds_bytes': 0, 'named_barriers': 0,
    'entry': {'args': 'v0:v1; uniform global pointer to aligned 240-byte block',
              'linear_tid': 'v2; physical 1D threadIdx.x', 'EXEC': 'all 32 lanes active',
              'vgpr_bank': 0, 'block_threads': [128, 256]},
    'preserves_written_sgprs': list(range(30, 39)),
    'preserves_written_vgprs': list(range(40, 46)),
    'sgpr_backups': {'s30:s37': 's40:s47', 's38': 's5'},
    'vgpr_backups': {'v40:v45': 'v48:v53', 'MODE[7:0]': 'v54'},
    'mode_during_payload_low8': 192, 'mode_restored': True,
    'virtual_grid': [0, 0, 0], 'tile': [64, 64],
    'original_assembly_sha256': SOURCE_SHA, 'patches': manifest,
    'caller_resource_merge_required': True, 'scratch_allowed_in_caller': True,
    'gpu_validation': 'pending: no gfx1250 GPU locally',
}
(ROOT / 'resources.json').write_text(json.dumps(resources, indent=2) + '\n')
print('Generated dq_convert.device.s and resources.json')
